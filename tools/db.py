"""The database: a SQLite file on this computer, or PostgreSQL (Neon) when the site is online.

Set DATABASE_URL to a postgresql:// address (Neon shows it as the "connection string") to use
PostgreSQL; without it, data/puzzle.db is used. The rest of the app writes its SQL once, with
? placeholders and syntax both databases understand, and never needs to know which one it got.

Security choices:
- Every query is parameterised; values never become part of the SQL text.
- Connections to a database on another machine must be encrypted (TLS); a connection string
  asking for less is refused.
- Online, connections are pooled and closed after a minute without use, so the database can
  go to sleep (Neon's free plan counts the time it's awake).
"""

import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DATABASE_URL = os.environ.get("DATABASE_URL")
SAFE_SSL_MODES = {"require", "verify-ca", "verify-full"}


class Connection:
    """One connection, inside a transaction that commits when the `with` block ends without an error."""

    def __init__(self, raw, postgres):
        self.raw = raw
        self.postgres = postgres

    def execute(self, sql, params=()):
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.raw.execute(sql, params)


class Database:
    def __init__(self, sqlite_path, url=DATABASE_URL):
        self.postgres = bool(url)
        if self.postgres:
            import psycopg
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool

            self.IntegrityError = psycopg.IntegrityError
            self.pool = ConnectionPool(
                secure_conninfo(url),
                min_size=0,
                max_size=4,
                max_idle=60,
                check=ConnectionPool.check_connection,  # replaces connections the database closed while asleep
                kwargs={"row_factory": dict_row, "prepare_threshold": None},
                open=True,
            )
        else:
            self.IntegrityError = sqlite3.IntegrityError
            self.path = Path(sqlite_path)
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.connect() as db:
                db.execute("PRAGMA journal_mode = WAL")
            try:
                # Only this user can open the folder, so the database and SQLite's -wal/-shm files stay private.
                self.path.parent.chmod(0o700)
                self.path.chmod(0o600)
            except OSError:
                pass

    @contextmanager
    def connect(self):
        if self.postgres:
            with self.pool.connection() as raw:  # commits, or rolls back on an error
                yield Connection(raw, True)
            return
        raw = sqlite3.connect(self.path, timeout=10)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys = ON")
        try:
            with raw:  # commits, or rolls back on an error
                yield Connection(raw, False)
        finally:
            raw.close()

    def script(self, sql):
        """Runs CREATE statements written for SQLite, adjusting the column types for PostgreSQL."""
        if self.postgres:
            sql = re.sub(r"\bid INTEGER PRIMARY KEY\b", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
            sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)  # times are stored in milliseconds
            sql = re.sub(r"\bBLOB\b", "BYTEA", sql)
        with self.connect() as db:
            for statement in sql.split(";"):
                if statement.strip():
                    db.execute(statement)

    def size(self, db):
        """How much room the whole database takes now, in bytes (tables, indexes and all)."""
        if self.postgres:
            return int(db.execute("SELECT pg_database_size(current_database()) AS n").fetchone()["n"])
        pages = db.execute("PRAGMA page_count").fetchone()[0]
        size = db.execute("PRAGMA page_size").fetchone()[0]
        return int(pages * size)

    def add_column(self, table, column, definition):
        """Adds a column to a table made by an older version of the app, if it's missing."""
        with self.connect() as db:
            if self.postgres:
                definition = re.sub(r"\bINTEGER\b", "BIGINT", definition)
                db.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {definition}")
            elif column not in {r["name"] for r in db.execute(f"PRAGMA table_info({table})")}:
                db.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")


def secure_conninfo(url):
    """The connection string, refusing unencrypted connections to anything but this computer."""
    from psycopg.conninfo import conninfo_to_dict, make_conninfo

    params = conninfo_to_dict(url)
    local = params.get("host") in ("localhost", "127.0.0.1", "::1")
    if not local and params.get("sslmode") not in SAFE_SSL_MODES:
        if params.get("sslmode") not in (None, "prefer"):
            raise SystemExit("DATABASE_URL must use an encrypted connection (sslmode=require).")
        params["sslmode"] = "require"
    return make_conninfo(**params)
